package com.mailshield.model;

import com.mailshield.dto.IndicatorToken;

import java.util.List;

/**
 * Encapsulates the complete prediction result computed by Multinomial Naive Bayes.
 */
public record PredictionResult(
        String predictedLabel,
        double spamProbability,
        double hamProbability,
        double logPriorSpam,
        double logPriorHam,
        double logLikelihoodSpam,
        double logLikelihoodHam,
        double totalLogScoreSpam,
        double totalLogScoreHam,
        int totalTokens,
        int recognizedTokens,
        int unknownTokens,
        List<IndicatorToken> topSpamIndicators,
        List<IndicatorToken> topHamIndicators,
        String explanation,
        String disclaimer
) {
    public static final String DISCLAIMER_TEXT =
            "Predictions are probabilistic machine learning estimates generated by a Multinomial Naive Bayes model. " +
            "A HAM classification does NOT guarantee an email is completely safe or authentic. " +
            "Always inspect sender headers, attachment signatures, and suspicious links with caution.";
}
